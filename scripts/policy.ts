// Hit rates of LRU and TinyLFU on synthetic workloads, plus operation cost against capacity. No I/O.
import { mkdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import { LruCache } from "../src/cache/lru.js";
import { TinyLfu } from "../src/cache/tinylfu.js";
import { mulberry32, zipf } from "./lib.js";

const KEYS = 50_000;
const REQUESTS = 1_000_000;

type Workload = () => string;
const workloads: Array<{ name: string; make: () => Workload }> = [
  ...[0.8, 1.0].map((s) => ({
    name: `Zipf, exponent ${s.toFixed(1)}`,
    make: () => {
      const draw = zipf(KEYS, s, mulberry32(11));
      return () => `k${draw()}`;
    },
  })),
  {
    name: "Zipf 1.0 with 30% one-off scans",
    make: () => {
      const random = mulberry32(12);
      const draw = zipf(KEYS, 1, mulberry32(13));
      let scan = 0;
      return () => (random() < 0.3 ? `scan${scan++}` : `k${draw()}`);
    },
  },
];

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;

function hitRate(cache: LruCache<number>, next: Workload, requests: number): number {
  let hits = 0;
  for (let i = 0; i < requests; i++) {
    const key = next();
    if (cache.get(key) !== undefined) hits++;
    else cache.set(key, 1);
  }
  return hits / requests;
}

const rows: string[] = [];
for (const w of workloads) {
  for (const fraction of [0.01, 0.05, 0.1]) {
    const capacity = Math.round(KEYS * fraction);
    const lru = hitRate(new LruCache<number>(capacity), w.make(), REQUESTS);
    const lfu = hitRate(new LruCache<number>(capacity, new TinyLfu(capacity)), w.make(), REQUESTS);
    rows.push(`| ${w.name} | ${pct(fraction)} | ${pct(lru)} | ${pct(lfu)} | ${((lfu - lru) * 100).toFixed(1)} |`);
  }
}

// The trade-off: after popularity changes completely, how quickly does each policy recover?
const shiftRows: string[] = [];
{
  const capacity = KEYS * 0.05;
  const WINDOW = 20_000;
  const caches = {
    LRU: new LruCache<number>(capacity),
    TinyLFU: new LruCache<number>(capacity, new TinyLfu(capacity)),
  };
  const result: Record<string, number[]> = {};
  for (const [name, cache] of Object.entries(caches)) {
    const draw = zipf(KEYS, 1, mulberry32(14));
    hitRate(cache, () => `old${draw()}`, 500_000);
    result[name] = Array.from({ length: 5 }, () => hitRate(cache, () => `new${draw()}`, WINDOW));
  }
  for (let i = 0; i < 5; i++) {
    shiftRows.push(`| ${(i * WINDOW).toLocaleString("en")} to ${((i + 1) * WINDOW).toLocaleString("en")} | ${pct(result.LRU[i])} | ${pct(result.TinyLFU[i])} |`);
  }
}

const costRows: string[] = [];
for (const capacity of [1_000, 10_000, 100_000, 1_000_000]) {
  const keys = Array.from({ length: capacity * 2 }, (_, i) => `k${i}`);
  const random = mulberry32(15);
  const picks = Uint32Array.from({ length: 1_000_000 }, () => Math.floor(random() * keys.length));
  const cost = (cache: LruCache<number>) => {
    for (let i = 0; i < capacity; i++) cache.set(keys[i], 1);
    const t = performance.now();
    for (let i = 0; i < picks.length; i++) {
      const key = keys[picks[i]];
      if (cache.get(key) === undefined) cache.set(key, 1);
    }
    return ((performance.now() - t) * 1e6) / picks.length;
  };
  costRows.push(`| ${capacity.toLocaleString("en")} | ${cost(new LruCache(capacity)).toFixed(0)} | ${cost(new LruCache(capacity, new TinyLfu(capacity))).toFixed(0)} |`);
}

const md = `# Eviction policy comparison

Generated by \`npm run bench:policy\` on ${new Date().toISOString().slice(0, 10)}. Simulation with seeded random input: ${KEYS.toLocaleString("en")} keys and ${REQUESTS.toLocaleString("en")} requests per row, including cold start. Hit rates are reproducible. Timings are from ${os.cpus()[0].model.trim()}, Node ${process.version}.

## Hit rate

| Workload | Capacity (share of keys) | LRU | TinyLFU | Difference (points) |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

## Recovery after popularity changes completely

Capacity is 5% of keys. Every popular key is replaced by a new one, with the same distribution.

| Requests after the change | LRU | TinyLFU |
| --- | --- | --- |
${shiftRows.join("\n")}

## Cost per read, with a set on a miss

Uniform random keys over twice the capacity, so about half of reads miss.

| Capacity | LRU (ns) | TinyLFU (ns) |
| --- | --- | --- |
${costRows.join("\n")}

The operation count is constant at every size. The time still grows with capacity, as more of the structure falls outside the CPU caches.
`;
mkdirSync("docs", { recursive: true });
writeFileSync("docs/policy-results.md", md);
console.log(md);
